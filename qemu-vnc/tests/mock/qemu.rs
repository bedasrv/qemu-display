//! A stand-in for the QEMU side of `org.qemu.Display1`.
//!
//! `qemu-vnc` is a D-Bus *client*: it asks a QEMU for its consoles, listens to
//! their scanouts, and sends input back. Until now that half was only covered
//! by unit tests calling the listener callbacks directly, which cannot catch a
//! wrong signal name, a wrong property type, or a method that is never really
//! sent. This is the peer those tests were standing in for: a real object
//! server on the session bus, exporting the interfaces `qemu-display` proxies.
//!
//! It is deliberately not a QEMU. It has two consoles, records what the client
//! sends it, pushes pixels when a test tells it to, and — only for a VM that
//! advertises an audio device — serves `org.qemu.Display1.Audio` and takes back
//! a socket for the audio out listener. What it does have is the
//! *real* D-Bus surface, so the client is exercised over a real connection.
//!
//! # The listener
//!
//! The one part that is not a plain method call is the console listener. The
//! client calls `Console.RegisterListener()` with one end of a socket pair and
//! then serves `org.qemu.Display1.Listener` on the *other* end, over a
//! peer-to-peer connection. The mock takes that connection and pushes the
//! scanouts down it, which is the direction QEMU's `ui/dbus-display.c` pushes
//! them in.

// `org.qemu.Display1.Listener.Update` takes seven arguments, so a proxy for it
// has a method with eight, and clippy says so. The method is generated by the
// `zbus::proxy` macro from the interface, and the interface is QEMU's, so
// neither the arity nor the lint's reach into the generated code is ours to
// change. This is the only thing the allow covers in this file.
#![allow(clippy::too_many_arguments)]
// Two test binaries share this file -- `mock.rs` and `dbus_cost.rs` -- and each
// uses a different part of it. A helper that `dbus_cost.rs` has no use for is
// not dead code in the mock; it is a helper one of its two users does not
// currently need. Without this, every binary but the fullest reports the whole
// fixture as unused, and the answer to that is a `#[allow]`, not deleting the
// other user's code.
#![allow(dead_code)]

use std::collections::HashMap;
use std::sync::{Arc, Mutex};

use qemu_display::{ClipboardSelection, MouseButton};
use serde_bytes::ByteBuf;
use zbus::Connection;
use zbus::Guid;
use zbus::{Fd, ObjectPath};

/// The pixman format of the pixels the mock pushes, as QEMU's scanouts carry
/// them: `x8r8g8b8`, little endian, with the depth of 24.
pub const PIXMAN_X8R8G8B8: u32 = 0x2002_0888;

/// `r5g6b5`: five bits of red, six of green, five of blue. A console whose
/// guest asked for a different format than the server's native one.
pub const PIXMAN_R5G6B5: u32 = 0x1001_0615;

/// `a8r8g8b8`: the same colours as [`PIXMAN_X8R8G8B8`] with an alpha byte, and
/// the other of the two formats a scanout normally arrives in. Little endian,
/// so the bytes of a pixel are blue, green, red, alpha — the reverse of the
/// order they are usually written down in.
pub const PIXMAN_A8R8G8B8: u32 = 0x2003_8888;

/// A format no display uses, and one the server cannot read.
pub const PIXMAN_UNUSABLE: u32 = 0x2002_8888;

/// How many consoles the mock exports, as `ConsoleIDs` claims.
pub const CONSOLES: u32 = 2;

/// How many times a test asks again before it gives up. The wait is a poll, so
/// a test that is going to succeed usually succeeds at once; the count only
/// decides how long a failure takes to be reported.
pub const ATTEMPTS: usize = 40;

/// How many bytes one pixel of `format` is.
///
/// A stride is not decoration: the server reads each row of a scanout at it, so
/// a scanout in `r5g6b5` with an `x8r8g8b8` stride is read as garbage rather
/// than as the wrong colour.
pub fn bytes_per_pixel(format: u32) -> u32 {
    match format {
        PIXMAN_R5G6B5 => 2,
        _ => BYTES_PER_PIXEL,
    }
}

/// The bytes one pixel of that format is.
pub const BYTES_PER_PIXEL: u32 = 4;

/// The object path of the VM, as `qemu-display` asks for it.
/// An anonymous memory file, for `ScanoutMap` to pass by descriptor.
///
/// **A memory file and not a temporary one**, because the descriptor is what
/// crosses the bus and what the client maps. A temporary file would exercise the
/// same zbus code with a different backing object, which is close enough to be
/// reassuring and different enough to matter: `memfd` has no name, so there is
/// nothing for the client's `mmap` to resolve, and the only thing it can use is
/// the descriptor it was given.
fn memfd(name: &str) -> std::io::Result<std::fs::File> {
    use std::os::fd::{FromRawFd, OwnedFd};
    let name = std::ffi::CString::new(name).expect("a name with no interior zero");
    // SAFETY: `memfd_create` either returns a fresh descriptor or -1, and a -1
    // is turned into an error rather than a file. The flags are MFD_CLOEXEC
    // alone, so the file is writable and is not sealed.
    let fd = unsafe { libc::memfd_create(name.as_ptr(), libc::MFD_CLOEXEC) };
    if fd < 0 {
        return Err(std::io::Error::last_os_error());
    }
    Ok(unsafe { std::fs::File::from(OwnedFd::from_raw_fd(fd)) })
}

pub const VM_PATH: &str = "/org/qemu/Display1/VM";

/// The object path of the listener, on the peer-to-peer connection.
pub const LISTENER_PATH: &str = "/org/qemu/Display1/Listener";

/// The object path of the object manager, which QEMU serves on the display root.
pub const OBJECT_MANAGER_PATH: &str = "/org/qemu/Display1";

/// The object path of the audio interface, which exists only on a VM that has
/// an audio device.
pub const AUDIO_PATH: &str = "/org/qemu/Display1/Audio";

/// Where the client serves the audio out listener, on the far end of the socket
/// pair that `RegisterOutListener` hands over. Spelled out here rather than
/// imported because `qemu-display` has it as a literal in
/// `Audio::register_out_listener`, and a test that used the wrong one would
/// build a proxy for an object nobody serves.
pub const AUDIO_OUT_LISTENER_PATH: &str = "/org/qemu/Display1/AudioOutListener";

/// The object path of the clipboard, which has no index: QEMU has one.
pub const CLIPBOARD_PATH: &str = "/org/qemu/Display1/Clipboard";

/// The object path of a console, as QEMU names them.
pub fn console_path(index: u32) -> String {
    format!("/org/qemu/Display1/Console_{index}")
}

/// A key the client pressed or released.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Key {
    /// The keycode, as `Keyboard.PressKey` takes it.
    pub keycode: u32,
    /// Whether it went down.
    pub down: bool,
}

/// A mouse event the client sent.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Mouse {
    /// A button went down or up.
    Button { button: MouseButton, down: bool },
    /// The pointer moved, in the device's own coordinates.
    Abs { x: u32, y: u32 },
    /// The pointer moved by a delta, for a relative device.
    Rel { dx: i32, dy: i32 },
}

/// A clipboard grab the client asked for.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Grab {
    /// Which selection was grabbed.
    pub selection: ClipboardSelection,
    /// The mime types the client will take.
    pub mimes: Vec<String>,
}

/// Everything the mock recorded the client doing.
#[derive(Debug, Default)]
pub struct Recorded {
    /// The keys, in the order they were pressed and released.
    pub keys: Vec<Key>,
    /// The mouse events, in order.
    pub mouse: Vec<Mouse>,
    /// The clipboard grabs.
    pub grabs: Vec<Grab>,
    /// Whether the client claimed the pointer, and with what.
    pub mouse_set: Vec<(bool, bool)>,
    /// The `SetUIInfo` calls a resizing client made.
    pub ui_info: Vec<(u32, u32)>,
    /// Whether the console's listener was registered.
    pub listener_registered: bool,
    /// Whether the clipboard peer registered.
    pub clipboard_registered: bool,
}

/// The mock QEMU: an object server, and what the client has done to it.
pub struct MockQemu {
    connection: Connection,
    /// The pixel size of each console, by index.
    sizes: HashMap<u32, (u32, u32)>,
    /// The peer-to-peer connection each console's listener is served on, once
    /// the client has registered one. A test that pushes to the wrong console
    /// would silently test nothing, so the index is part of the key rather than
    /// a single slot.
    listeners: Arc<Mutex<HashMap<u32, Connection>>>,
    /// The memory file handed to each console by `ScanoutMap`, kept so a test
    /// can go on writing the pixels it says it wrote.
    mapped: Arc<Mutex<HashMap<u32, std::fs::File>>>,
    /// What the client has done.
    recorded: Arc<Mutex<Recorded>>,
    /// The clipboard content the mock is holding, which a test changes to
    /// stand in for the guest copying something.
    clipboard: Arc<Mutex<String>>,
    /// The peer-to-peer connection the audio out listener is served on, once
    /// the client has registered one.
    ///
    /// Single-slot rather than keyed by console: QEMU has one audio interface
    /// for the whole VM, not one per console, so a map here would let a test
    /// push to a stream the client never asked for.
    audio_listener: Arc<Mutex<Option<Connection>>>,
}

impl MockQemu {
    /// Export the interfaces, and hand back the connection a client uses.
    ///
    /// The two ends are a peer-to-peer socket pair rather than a bus, which is
    /// what `--dbus-p2p-fd` gives the real program. It is the right shape for
    /// tests for two reasons: nothing has to own the `org.qemu` well-known
    /// name, so parallel tests do not fight over it; and there is no bus to be
    /// absent, so a test never skips.
    pub async fn start(size: (u32, u32)) -> Result<(Self, Connection), zbus::Error> {
        Self::start_with_audio(size, false).await
    }

    /// [`start`], for a VM that does or does not have an audio device.
    pub async fn start_with_audio(
        size: (u32, u32),
        audio: bool,
    ) -> Result<(Self, Connection), zbus::Error> {
        use std::os::fd::IntoRawFd;

        let (ours, theirs) = std::os::unix::net::UnixStream::pair()?;
        let listeners = Arc::new(Mutex::new(HashMap::new()));
        // The object manager is part of the connection rather than the object
        // server, because it has to exist before the connection is built.
        let objects = managed_objects((0..CONSOLES).collect(), audio);

        // Both ends at once, which the peer-to-peer handshake requires: the
        // side that was handed a connection waits to be authenticated, and the
        // side that handed one over drives it. Building them in sequence waits
        // for ever. The mock is the server end — the one that waits — because
        // that is the role QEMU has in `--dbus-p2p-fd`.
        let ours = zbus::connection::Builder::unix_stream(ours)
            .server(Guid::generate())
            .p2p()
            .serve_at("/", Health)
            .serve_at(OBJECT_MANAGER_PATH, ObjectManager { objects })
            .build();
        let theirs = qemu_vnc::utils::p2p_from_fd(theirs.into_raw_fd());
        let (connection, client) = futures::future::join(ours, theirs).await;
        let connection = connection?;
        let client = client.map_err(|e| zbus::Error::Failure(e.to_string()))?;
        let recorded = Arc::new(Mutex::new(Recorded::default()));
        let clipboard = Arc::new(Mutex::new(String::new()));
        // Every console the same size but the first: a test that switches
        // between them can tell the pixels apart by colour, and one that only
        // wants the first does not have to care.
        let sizes: HashMap<u32, (u32, u32)> = (0..CONSOLES).map(|index| (index, size)).collect();

        connection.object_server().at(VM_PATH, Vm { size }).await?;
        // The keyboard and the mouse are on the console's own path, as QEMU
        // has them: one object, three interfaces, and one type per interface
        // because a type can have only one.
        for index in 0..CONSOLES {
            let path = ObjectPath::try_from(console_path(index)).expect("a valid path");
            let size = sizes[&index];
            connection
                .object_server()
                .at(
                    path.clone(),
                    Console {
                        index,
                        size,
                        listeners: listeners.clone(),
                        recorded: recorded.clone(),
                    },
                )
                .await?;
            connection
                .object_server()
                .at(
                    path.clone(),
                    Input {
                        recorded: recorded.clone(),
                    },
                )
                .await?;
            connection
                .object_server()
                .at(
                    path,
                    MouseInput {
                        recorded: recorded.clone(),
                    },
                )
                .await?;
        }
        connection
            .object_server()
            .at(
                CLIPBOARD_PATH,
                Clipboard {
                    recorded: recorded.clone(),
                    data: clipboard.clone(),
                },
            )
            .await?;
        // The audio interface is served only for a VM that has one, because
        // that is the whole question `Display::has_audio` asks, and an object
        // that was here unconditionally would answer it wrongly.
        let audio_listener = Arc::new(Mutex::new(None));
        if audio {
            connection
                .object_server()
                .at(
                    ObjectPath::try_from(AUDIO_PATH).expect("a valid path"),
                    AudioRegistration {
                        listener: audio_listener.clone(),
                    },
                )
                .await?;
        }

        Ok((
            Self {
                connection,
                sizes,
                listeners,
                mapped: Arc::default(),
                recorded,
                clipboard,
                audio_listener,
            },
            client,
        ))
    }

    /// A console's size.
    pub fn size(&self, index: u32) -> (u32, u32) {
        self.sizes[&index]
    }

    /// Change a console's pixel size, as a guest switching video mode does.
    ///
    /// The server learns the new size from the next scanout, so this is what a
    /// test needs before pushing a frame of a different size: the mock
    /// otherwise announces its own size with data of another, and the two
    /// disagree.
    pub fn resize(&mut self, index: u32, size: (u32, u32)) {
        self.sizes.insert(index, size);
    }

    /// What the client has done, as it stands.
    pub fn recorded(&self) -> Recorded {
        let recorded = self.recorded.lock().unwrap();
        Recorded {
            keys: recorded.keys.clone(),
            mouse: recorded.mouse.clone(),
            grabs: recorded.grabs.clone(),
            mouse_set: recorded.mouse_set.clone(),
            ui_info: recorded.ui_info.clone(),
            listener_registered: recorded.listener_registered,
            clipboard_registered: recorded.clipboard_registered,
        }
    }

    /// The keys the client sent, in order.
    pub fn keys(&self) -> Vec<Key> {
        self.recorded().keys
    }

    /// The mouse events the client sent, in order.
    pub fn mouse(&self) -> Vec<Mouse> {
        self.recorded().mouse
    }

    /// The clipboard grabs the client asked for.
    pub fn grabs(&self) -> Vec<Grab> {
        self.recorded().grabs
    }

    /// Whether the client registered a console's listener.
    ///
    /// The push methods need this: before the client has registered, there is
    /// no connection to push on.
    pub fn is_registered(&self, index: u32) -> bool {
        self.listeners.lock().unwrap().contains_key(&index)
    }

    /// Wait until the client has registered a console's listener.
    pub async fn wait_registered(&self, index: u32) {
        for _ in 0..ATTEMPTS {
            if self.is_registered(index) {
                return;
            }
            async_io::Timer::after(std::time::Duration::from_millis(5)).await;
        }
        panic!("the client never registered a listener for console {index}");
    }

    /// Whether the client registered the audio out listener.
    pub fn is_audio_registered(&self) -> bool {
        self.audio_listener.lock().unwrap().is_some()
    }

    /// Wait until the client has registered the audio out listener.
    pub async fn wait_audio_registered(&self) {
        for _ in 0..ATTEMPTS {
            if self.is_audio_registered() {
                return;
            }
            async_io::Timer::after(std::time::Duration::from_millis(5)).await;
        }
        panic!("the client never registered the audio out listener");
    }

    /// Push a block of guest samples, as QEMU does once its audio engine has
    /// captured some.
    ///
    /// `Init` then `Write`, in the order `c/audio.c` handles them: the client is
    /// told what the stream looks like before any samples arrive, and `Write`
    /// carries the id it was initialised with. `bytes_per_frame` and
    /// `bytes_per_second` are worked out here rather than passed in, because a
    /// test that disagreed with them about the format would be asserting that
    /// QEMU lies rather than that anything arrived.
    #[allow(clippy::too_many_arguments)]
    pub async fn push_audio(
        &self,
        id: u64,
        bits: u8,
        is_signed: bool,
        freq: u32,
        nchannels: u8,
        samples: &[u8],
    ) -> zbus::Result<()> {
        self.push_audio_as(id, bits, is_signed, false, freq, nchannels, samples)
            .await
    }

    /// [`push_audio`], for a stream whose samples are IEEE floats.
    ///
    /// A separate method rather than a parameter because `is_float` is the one
    /// field of `Init` the port has never read, and a fixture that cannot send
    /// it is a fixture that cannot catch what that costs.
    #[allow(clippy::too_many_arguments)]
    pub async fn push_audio_as(
        &self,
        id: u64,
        bits: u8,
        is_signed: bool,
        is_float: bool,
        freq: u32,
        nchannels: u8,
        samples: &[u8],
    ) -> zbus::Result<()> {
        let bytes_per_frame = u32::from(bits / 8) * u32::from(nchannels);
        let proxy = self.audio_proxy().await?;
        proxy
            .init(
                id,
                bits,
                is_signed,
                is_float,
                freq,
                nchannels,
                bytes_per_frame,
                freq * bytes_per_frame,
                false,
            )
            .await?;
        proxy.write(id, ByteBuf::from(samples.to_vec())).await?;
        Ok(())
    }

    /// A proxy for the client's audio out listener.
    ///
    /// Built on the peer-to-peer connection rather than the one the mock's
    /// objects are on, for the same reason `connection_of` says: a proxy on the
    /// session bus would find the mock's objects and never the client's, so a
    /// test would pass and prove nothing.
    async fn audio_proxy(&self) -> zbus::Result<ClientAudioListenerProxy<'_>> {
        let listener = self.audio_listener.lock().unwrap().clone().ok_or_else(|| {
            zbus::Error::Failure("no audio out listener is registered".to_string())
        })?;
        ClientAudioListenerProxy::builder(&listener)
            .destination("org.qemu".to_string())
            .path(AUDIO_OUT_LISTENER_PATH)
            .build()
            .await
    }

    /// Push a whole console to the client, as a new scanout.
    pub async fn scanout(&self, index: u32, data: Vec<u8>) -> zbus::Result<()> {
        self.scanout_as(index, PIXMAN_X8R8G8B8, data).await
    }

    /// Push a whole console in `format`, which is what a console whose guest
    /// picked its own pixel format sends.
    pub async fn scanout_as(&self, index: u32, format: u32, data: Vec<u8>) -> zbus::Result<()> {
        let (width, height) = self.size(index);
        self.listener(index)
            .await?
            .scanout(
                width,
                height,
                width * bytes_per_pixel(format),
                format,
                ByteBuf::from(data),
            )
            .await
    }

    /// Push a rectangle of the console to the client, as an update.
    pub async fn update(
        &self,
        index: u32,
        rect: (i32, i32, i32, i32),
        data: Vec<u8>,
    ) -> zbus::Result<()> {
        let (x, y, w, h) = rect;
        self.listener(index)
            .await?
            .update(
                x,
                y,
                w,
                h,
                (w as u32) * BYTES_PER_PIXEL,
                PIXMAN_X8R8G8B8,
                ByteBuf::from(data),
            )
            .await
    }

    /// Set the cursor, as `CursorDefine` does.
    pub async fn cursor(
        &self,
        index: u32,
        (width, height): (i32, i32),
        hotspot: (i32, i32),
        data: Vec<u8>,
    ) -> zbus::Result<()> {
        self.listener(index)
            .await?
            .cursor_define(width, height, hotspot.0, hotspot.1, data)
            .await
    }

    /// Offer the clipboard to the client, as QEMU does when the guest copies.
    ///
    /// A request and not a signal, which is what `ClipboardPeer` implements:
    /// the guest calls the client's `Grab`, and the client then asks the guest
    /// for the data with `Request`, and only then sends it to its viewers as a
    /// cut text.
    pub async fn offer_clipboard(&self, data: &str) -> zbus::Result<()> {
        *self.clipboard.lock().unwrap() = data.to_owned();
        let peer = ClientClipboardProxy::builder(&self.connection)
            .path(CLIPBOARD_PATH)
            .build()
            .await?;
        peer.grab(
            ClipboardSelection::Clipboard,
            0,
            vec!["text/plain;charset=utf-8".to_owned()],
        )
        .await?;
        Ok(())
    }

    /// The client's `interfaces` property, which is what QEMU reads to decide
    /// whether to offer a map.
    pub async fn listener_interfaces(&self, index: u32) -> zbus::Result<Vec<String>> {
        let connection = self.connection_of(index).await?;
        ClientListenerInterfacesProxy::builder(&connection)
            .path(LISTENER_PATH)
            .build()
            .await?
            .interfaces()
            .await
    }

    /// Offer the client a mapping of the console, as QEMU does with
    /// `ScanoutMap`.
    ///
    /// The surface goes into a **memory file** that is passed over D-Bus by
    /// its descriptor, because that is the whole mechanism: a name or a path
    /// would not be the same thing, and the test would pass while the real
    /// descriptor passing was broken.
    pub async fn scanout_map(
        &self,
        index: u32,
        data: Vec<u8>,
    ) -> zbus::Result<std::fs::File> {
        use std::io::Write as _;
        use std::os::fd::AsFd as _;

        let (width, height) = self.size(index);
        let stride = width * BYTES_PER_PIXEL;
        assert_eq!(
            data.len(),
            stride as usize * height as usize,
            "the mock's surface is the wrong size for the console it is mapping"
        );
        let mut file = memfd("qemu-vnc-mock-scanout")?;
        file.write_all(&data).expect("the surface fits the memory file");
        let connection = self.connection_of(index).await?;
        ClientListenerMapProxy::builder(&connection)
            .path(LISTENER_PATH)
            .build()
            .await?
            .scanout_map(
                // From a borrowed descriptor, so the mock keeps ownership of
                // the file and can go on writing the pixels it says it wrote.
                zbus::Fd::from(file.as_fd()),
                0,
                width,
                height,
                stride,
                PIXMAN_X8R8G8B8,
            )
            .await?;
        // Kept so a test can go on writing into the same mapping. A *second*
        // file handle over the same memory file, not a move: the descriptor
        // already crossed the bus, and what the test needs afterwards is the
        // offset it is at, which is the same object either way.
        self.mapped.lock().unwrap().insert(index, file.try_clone()?);
        Ok(file)
    }

    /// Name a rectangle of the mapping that has changed, and write the pixels
    /// for it first, in the order QEMU does: the write happens before the
    /// message, because the client is entitled to read them when it arrives.
    pub async fn update_map(
        &self,
        index: u32,
        rect: (i32, i32, i32, i32),
        pixels: &[u8],
    ) -> zbus::Result<()> {
        use std::io::{Seek, SeekFrom, Write as _};

        let (x, y, w, h) = rect;
        let mut file = {
            let mapped = self.mapped.lock().unwrap();
            mapped
                .get(&index)
                .ok_or_else(|| {
                    zbus::Error::Failure(format!("no mapping is offered for console {index}"))
                })?
                .try_clone()?
        };
        let stride = self.size(index).0 * BYTES_PER_PIXEL;
        assert_eq!(
            pixels.len(),
            (w as u32 * BYTES_PER_PIXEL) as usize * h as usize,
            "the mock is asked to name a {w}x{h} rectangle and given {} bytes, \
             which is not what it is about to tell the client it wrote",
            pixels.len()
        );
        let row_bytes = w as usize * BYTES_PER_PIXEL as usize;
        for row in 0..h {
            let at = (y as u32 + row as u32) * stride + x as u32 * BYTES_PER_PIXEL;
            file.seek(SeekFrom::Start(at.into()))
                .expect("a seekable memory file");
            let from = row as usize * row_bytes;
            file.write_all(&pixels[from..from + row_bytes])
                .expect("the rectangle fits the mapping");
        }
        let connection = self.connection_of(index).await?;
        ClientListenerMapProxy::builder(&connection)
            .path(LISTENER_PATH)
            .build()
            .await?
            .update_map(x, y, w, h)
            .await
    }

    /// A console's listener, once the client has registered one.
    async fn listener(&self, index: u32) -> zbus::Result<ClientListenerProxy<'static>> {
        let connection = self.connection_of(index).await?;
        // A peer-to-peer connection has no destination to name, only a path.
        ClientListenerProxy::builder(&connection)
            .path(LISTENER_PATH)
            .build()
            .await
    }

    /// The peer-to-peer connection a console's listener is served on.
    ///
    /// **This has to be the client's end of the socket pair, which is the whole
    /// point of the arrangement**: `RegisterListener` hands QEMU one end and the
    /// client serves `org.qemu.Display1.Listener` on the other, so a proxy built
    /// on the *session bus* would find the mock's objects but never the
    /// client's. One of those is a test that passes and proves nothing.
    async fn connection_of(&self, index: u32) -> zbus::Result<Connection> {
        let listeners = self.listeners.lock().unwrap();
        listeners.get(&index).cloned().ok_or_else(|| {
            zbus::Error::Failure(format!("no listener is registered for console {index}"))
        })
    }
}

/// `org.freedesktop.DBus.ObjectManager`, which QEMU serves at
/// `/org/qemu/Display1`.
///
/// A client reads this before anything else: it is how it learns which objects
/// the peer has, which is the only way to ask whether there is an audio
/// interface to register with rather than registering and being told no. The
/// mock served everything else on this connection but not this, so `Display`
/// could not be built against it at all.
struct ObjectManager {
    objects: zbus::fdo::ManagedObjects,
}

#[zbus::interface(name = "org.freedesktop.DBus.ObjectManager")]
impl ObjectManager {
    /// Every object the mock exports, and the properties on it.
    fn get_managed_objects(&self) -> zbus::fdo::ManagedObjects {
        self.objects.clone()
    }
}

/// One property value, as an object manager lists them.
fn value(v: zbus::Variant<'static>) -> zbus::OwnedVariant {
    zbus::OwnedVariant::try_from(v).expect("a value the object manager can carry")
}

/// The object list a QEMU with one VM, two consoles and a clipboard would
/// export.
///
/// `audio` is whether the VM has an audio device, because
/// `/org/qemu/Display1/Audio` only exists when it does — and that is the whole
/// question the audio gate asks. Both answers have to be testable, or "does
/// not claim to have audio" and "looked in the wrong place" look the same.
fn managed_objects(console_ids: Vec<u32>, audio: bool) -> zbus::fdo::ManagedObjects {
    use std::collections::HashMap;
    let props = |entries: Vec<(&str, zbus::OwnedVariant)>| -> HashMap<String, zbus::OwnedVariant> {
        entries
            .into_iter()
            .map(|(name, v)| (name.to_owned(), v))
            .collect()
    };
    type Interfaces =
        HashMap<zbus::names::OwnedInterfaceName, HashMap<String, zbus::OwnedVariant>>;
    let interfaces =
        |entries: Vec<(&str, HashMap<String, zbus::OwnedVariant>)>| -> Interfaces {
            entries
                .into_iter()
                .map(|(name, props)| {
                    (
                        zbus::names::OwnedInterfaceName::try_from(name.to_owned())
                            .expect("an interface name"),
                        props,
                    )
                })
                .collect()
        };
    let mut objects = HashMap::new();
    for (path, list) in [
        (
            VM_PATH,
            interfaces(vec![(
                "org.qemu.Display1.VM",
                props(vec![
                    ("Name", value(zbus::Variant::from("mock"))),
                    ("UUID", value(zbus::Variant::from(""))),
                    (
                        "ConsoleIDs",
                        value(zbus::Variant::from(console_ids)),
                    ),
                    (
                        "Interfaces",
                        value(zbus::Variant::from(Vec::<String>::new())),
                    ),
                ]),
            )]),
        ),
        (
            CLIPBOARD_PATH,
            interfaces(vec![(
                "org.qemu.Display1.Clipboard",
                props(vec![
                    (
                        "is-data-available",
                        value(zbus::Variant::from(false)),
                    ),
                    (
                        "mime-types",
                        value(zbus::Variant::from(Vec::<String>::new())),
                    ),
                ]),
            )]),
        ),
    ] {
        objects.insert(
            zbus::OwnedObjectPath::try_from(path.to_owned()).expect("an object path"),
            list,
        );
    }
    if audio {
        objects.insert(
            zbus::OwnedObjectPath::try_from(AUDIO_PATH).expect("an object path"),
            interfaces(vec![(
                "org.qemu.Display1.Audio",
                props(vec![(
                    "Interfaces",
                    value(zbus::Variant::from(Vec::<String>::new())),
                )]),
            )]),
        );
    }
    for index in 0..CONSOLES {
        objects.insert(
            zbus::OwnedObjectPath::try_from(console_path(index)).expect("a path"),
            interfaces(vec![(
                "org.qemu.Display1.Console",
                props(vec![
                    ("Label", value(zbus::Variant::from("mock"))),
                    ("Head", value(zbus::Variant::from(0u32))),
                    ("Type", value(zbus::Variant::from("virtio-gpu"))),
                    ("Width", value(zbus::Variant::from(64u32))),
                    ("Height", value(zbus::Variant::from(32u32))),
                    (
                        "Interfaces",
                        value(zbus::Variant::from(Vec::<String>::new())),
                    ),
                ]),
            )]),
        );
    }
    objects
}

