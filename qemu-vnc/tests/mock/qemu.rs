/// `org.qemu.Display1.Console`: the properties and the listener registration.
struct Console {
    /// Which console this is, which is what a listener is filed under.
    index: u32,
    size: (u32, u32),
    listeners: Arc<Mutex<HashMap<u32, Connection>>>,
    recorded: Arc<Mutex<Recorded>>,
}

#[zbus::interface(name = "org.qemu.Display1.Console")]
impl Console {
    /// The console's label, which the client shows.
    #[zbus(property)]
    fn label(&self) -> String {
        "mock".into()
    }

    /// The head the console is on.
    #[zbus(property)]
    fn head(&self) -> u32 {
        0
    }

    /// The kind of console, which the client checks before adding pixels.
    #[zbus(property, name = "Type")]
    fn type_(&self) -> String {
        "virtio-gpu".into()
    }

    /// The console's width, which the client reads *before* registering.
    #[zbus(property)]
    fn width(&self) -> u32 {
        self.size.0
    }

    /// The console's height.
    #[zbus(property)]
    fn height(&self) -> u32 {
        self.size.1
    }

    /// Register the client's listener.
    ///
    /// This is where the direction reverses: the client passes one end of a
    /// socket pair and serves the listener on the other, so the mock builds a
    /// peer-to-peer connection from what it is given and pushes the scanouts
    /// down it.
    async fn register_listener(&mut self, listener: Fd<'_>) -> zbus::fdo::Result<()> {
        use std::os::fd::{FromRawFd, IntoRawFd};

        // The client passed one end of a socket pair and serves the listener on
        // the other, so this is where the direction of the pixels reverses: the
        // mock builds a connection on what it was given and calls the client's
        // interface down it.
        let owned = std::os::fd::OwnedFd::try_from(listener)
            .map_err(|e| zbus::fdo::Error::Failed(format!("not a usable fd: {e}")))?;
        let stream = unsafe { std::os::unix::net::UnixStream::from_raw_fd(owned.into_raw_fd()) };

        // Built on a task of its own, and not awaited here, because the client
        // is waiting for this call to return before it builds *its* end of the
        // handshake. Building it in the handler would wait for a peer that is
        // waiting for us: the two ends have to be driven at the same time.
        let index = self.index;
        let slot = self.listeners.clone();
        std::thread::Builder::new()
            .name(format!("mock-listener-{index}"))
            .spawn(move || {
                async_io::block_on(async move {
                    let connection = zbus::connection::Builder::unix_stream(stream)
                        .server(Guid::generate())
                        .p2p()
                        .build()
                        .await
                        .expect("the listener end of the socket pair");
                    slot.lock().unwrap().insert(index, connection);
                });
            })
            .expect("a thread for the listener connection");
        self.recorded.lock().unwrap().listener_registered = true;
        Ok(())
    }

    /// A client that asked to be resized.
    #[zbus(name = "SetUIInfo")]
    fn set_ui_info(
        &mut self,
        _width_mm: u16,
        _height_mm: u16,
        _xoff: i32,
        _yoff: i32,
        width: u32,
        height: u32,
    ) {
        self.recorded.lock().unwrap().ui_info.push((width, height));
    }
}

/// `org.qemu.Display1.Audio`, which QEMU serves only on a VM that has an audio
/// device.
///
/// The same shape as the console listener and for the same reason: the client
/// calls `RegisterOutListener` with one end of a socket pair and serves
/// `org.qemu.Display1.AudioOutListener` on the other, so this is where the
/// direction reverses and the mock gets a peer-to-peer connection to push
/// samples down. QEMU's side of it is `ui/dbus-display1.c`, which is not in
/// this tree; `c/audio.c` is the same file's client half, and it is what the
/// argument order below was checked against.
struct AudioRegistration {
    listener: Arc<Mutex<Option<Connection>>>,
}

#[zbus::interface(name = "org.qemu.Display1.Audio")]
impl AudioRegistration {
    /// Take the client's end of the socket pair.
    async fn register_out_listener(&mut self, listener: Fd<'_>) -> zbus::fdo::Result<()> {
        use std::os::fd::{FromRawFd, IntoRawFd};

        let owned = std::os::fd::OwnedFd::try_from(listener)
            .map_err(|e| zbus::fdo::Error::Failed(format!("not a usable fd: {e}")))?;
        let stream = unsafe { std::os::unix::net::UnixStream::from_raw_fd(owned.into_raw_fd()) };

        // A thread of its own and not awaited here, for the reason
        // `Console::register_listener` gives: the client is waiting for this
        // call to return before it builds *its* end of the handshake, so
        // building it inline would wait for a peer that is waiting for us.
        let slot = self.listener.clone();
        std::thread::Builder::new()
            .name("mock-audio-listener".to_string())
            .spawn(move || {
                async_io::block_on(async move {
                    let connection = zbus::connection::Builder::unix_stream(stream)
                        .server(Guid::generate())
                        .p2p()
                        .build()
                        .await
                        .expect("the listener end of the socket pair");
                    *slot.lock().unwrap() = Some(connection);
                });
            })
            .expect("a thread for the audio listener connection");
        Ok(())
    }
}

/// `org.qemu.Display1.AudioOutListener`, the interface the client serves on
/// the far end of the socket pair.
///
/// A proxy rather than a direct call, because going through the peer-to-peer
/// connection is the point: a test that called `AudioServer::write` directly
/// would exercise the conversion and skip the file descriptor handoff, the
/// second connection and the dispatch that a real QEMU's samples travel over.
#[zbus::proxy(
    default_service = "org.qemu",
    interface = "org.qemu.Display1.AudioOutListener"
)]
trait ClientAudioListener {
    /// Tell the client what a stream's samples look like.
    fn init(
        &self,
        id: u64,
        bits: u8,
        is_signed: bool,
        is_float: bool,
        freq: u32,
        nchannels: u8,
        bytes_per_frame: u32,
        bytes_per_second: u32,
        be: bool,
    ) -> zbus::Result<()>;

    /// The stream is over.
    fn fini(&self, id: u64) -> zbus::Result<()>;

    /// The guest's audio has started or stopped.
    fn set_enabled(&self, id: u64, enabled: bool) -> zbus::Result<()>;

    /// The guest's volume, which the RFB path has no use for.
    fn set_volume(&self, id: u64, mute: bool, volume: ByteBuf) -> zbus::Result<()>;

    /// A block of samples.
    fn write(&self, id: u64, data: ByteBuf) -> zbus::Result<()>;
}

