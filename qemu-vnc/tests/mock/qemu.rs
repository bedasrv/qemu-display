/// `org.qemu.Display1.Clipboard`.
struct Clipboard {
    recorded: Arc<Mutex<Recorded>>,
    data: Arc<Mutex<String>>,
}

#[zbus::interface(name = "org.qemu.Display1.Clipboard")]
impl Clipboard {
    /// The client offers itself as the clipboard peer.
    fn register(&mut self) {
        self.recorded.lock().unwrap().clipboard_registered = true;
    }

    /// The client stops being the peer.
    fn unregister(&mut self) {
        self.recorded.lock().unwrap().clipboard_registered = false;
    }

    /// The client takes the clipboard, and says what it can take.
    fn grab(&mut self, selection: ClipboardSelection, _serial: u32, mimes: Vec<String>) {
        self.recorded
            .lock()
            .unwrap()
            .grabs
            .push(Grab { selection, mimes });
    }

    /// The client gives the clipboard back.
    fn release(&mut self, selection: ClipboardSelection) {
        self.recorded.lock().unwrap().grabs.push(Grab {
            selection,
            mimes: Vec::new(),
        });
    }

    /// The client asks for the content it was just offered.
    fn request(
        &mut self,
        _selection: ClipboardSelection,
        _mimes: Vec<String>,
    ) -> zbus::fdo::Result<(String, Vec<u8>)> {
        let data = self.data.lock().unwrap().clone();
        Ok(("text/plain;charset=utf-8".into(), data.into_bytes()))
    }
}
